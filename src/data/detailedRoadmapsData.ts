export interface GraphNodeResource {
  title: string;
  url: string;
  type: 'article' | 'video' | 'doc';
  provider: string;
  durationOrReadTime?: string;
}

export interface GraphNode {
  id: string;
  title: string;
  description: string;
  category: string;
  x: number;
  y: number;
  width?: number;
  height?: number;
  difficulty: 'Beginner' | 'Intermediate' | 'Advanced';
  estimatedHours: number;
  prerequisites: string[]; // parent node IDs
  resources: GraphNodeResource[];
  status?: 'not_started' | 'in_progress' | 'completed';
  stepNumber?: number; // Sequential step: 1, 2, 3...
  isMainStep?: boolean; // true = central highway milestone, false = sub-topic branch
  subTopicLabel?: string; // e.g. "Sub-topic", "Core Branch"
}

