export const AITimetableManager: React.FC<AITimetableManagerProps> = ({
  initialData,
  onUpdate,
  isReadOnlyPreview = false,
}) => {
  const { userProfile, role } = useAuth();
  const { isDark } = useTheme();
  const { showToast } = useToast();

  const userId = userProfile?.userId || 'guest';
  const timetableStorageKey = `academic_timetable_${userId}`;

  // Timetable State
  const [timetable, setTimetable] = useState<TimetableData>(() => {
    if (initialData) return initialData;
    try {
      const saved = localStorage.getItem(timetableStorageKey);
      if (saved) return JSON.parse(saved);
    } catch {}
    return defaultDemoTimetable;
  });

  // Track onUpdate callback in a ref to avoid effect dependency re-runs
  const onUpdateRef = useRef(onUpdate);
  useEffect(() => {
    onUpdateRef.current = onUpdate;
  }, [onUpdate]);

  // Keep synced if initialData changes externally (e.g. from copilot preview), checking deep equality via serialized string
  const lastSerializedInitialDataRef = useRef<string>(initialData ? JSON.stringify(initialData) : '');

  useEffect(() => {
    if (initialData) {
      const serialized = JSON.stringify(initialData);
      if (serialized !== lastSerializedInitialDataRef.current) {
        lastSerializedInitialDataRef.current = serialized;
        setTimetable(initialData);
      }
    }
  }, [initialData]);

  // Central state update helper: updates internal state, serializes to localStorage, and calls onUpdate callback only on user mutations
  const updateTimetableState = (updater: (prev: TimetableData) => TimetableData) => {
    setTimetable((prev) => {
      const next = updater(prev);
      lastSerializedInitialDataRef.current = JSON.stringify(next);
      if (!isReadOnlyPreview) {
        try {
          localStorage.setItem(timetableStorageKey, JSON.stringify(next));
        } catch {}
      }
      onUpdateRef.current?.(next);
      return next;
    });
  };

  // Modal State for adding/editing a slot
  const [editingSlot, setEditingSlot] = useState<TimetableSlot | null>(null);
  const [modalOpen, setModalOpen] = useState(false);

  // Check for any schedule conflicts (same day + same periodIndex with > 1 slot)
  const slotConflictMap: Record<string, boolean> = {};
  const slotCountMap: Record<string, number> = {};

  timetable.slots.forEach((s) => {
    const key = `${s.day}-${s.periodIndex}`;
    slotCountMap[key] = (slotCountMap[key] || 0) + 1;
    if (slotCountMap[key] > 1) {
      slotConflictMap[key] = true;
    }
  });

  const hasConflicts = Object.keys(slotConflictMap).length > 0;

  // Open modal to add slot
  const handleOpenAddSlot = (day: string, periodIndex: number) => {
    if (isReadOnlyPreview) return;
    const periodDef = timetable.periodTimes[periodIndex] || {
      startTime: '09:00',
      endTime: '09:50',
    };

    setEditingSlot({
      id: `slot-${Date.now()}-${Math.random().toString(36).substring(2, 6)}`,
      day: day as any,
      periodIndex,
      startTime: periodDef.startTime,
      endTime: periodDef.endTime,
      subject: '',
      courseCode: '',
      instructor: '',
      room: '',
      type: 'lecture',
      color: '#00F0FF',
    });
    setModalOpen(true);
  };

  // Save slot
  const handleSaveSlot = (slot: TimetableSlot) => {
    if (!slot.subject.trim()) {
      showToast('Subject title is required.', 'warning');
      return;
    }

    updateTimetableState((prev) => {
      const exists = prev.slots.some((s) => s.id === slot.id);
      const updatedSlots = exists
        ? prev.slots.map((s) => (s.id === slot.id ? slot : s))
        : [...prev.slots, slot];
      return { ...prev, slots: updatedSlots };
    });

    setModalOpen(false);
    setEditingSlot(null);
    showToast(`Slot "${slot.subject}" updated.`, 'success');
  };

  // Delete slot
  const handleDeleteSlot = (id: string, e?: React.MouseEvent) => {
    if (e) e.stopPropagation();
    if (isReadOnlyPreview) return;
    updateTimetableState((prev) => ({
      ...prev,
      slots: prev.slots.filter((s) => s.id !== id),
    }));
    showToast('Class slot removed.', 'info');
  };

  // AI Auto-Balancing Routine
  const handleAIAutoOptimize = () => {
    showToast('AI Timetable Engine re-balancing schedule for zero conflicts...', 'info');
    setTimeout(() => {
      updateTimetableState((prev) => ({
        ...prev,
        slots: defaultDemoTimetable.slots,
        conflictDetected: false,
      }));
      showToast('Timetable optimized! Zero conflicts across 14 weekly contact hours.', 'success');
    }, 600);
  };

  // Export Timetable
  const handleExportJSON = () => {
    const dataStr = 'data:text/json;charset=utf-8,' + encodeURIComponent(JSON.stringify(timetable, null, 2));
    const downloadAnchor = document.createElement('a');
    downloadAnchor.setAttribute('href', dataStr);
    downloadAnchor.setAttribute('download', `${timetable.title.replace(/\s+/g, '_')}.json`);
    document.body.appendChild(downloadAnchor);
    downloadAnchor.click();
    downloadAnchor.remove();
    showToast('Timetable exported as JSON.', 'success');
  };

  return (
    <div className="max-w-7xl mx-auto p-4 md:p-6 space-y-6">
      {/* Top Header */}
      <div className="p-6 rounded-3xl border bg-gradient-to-br from-indigo-950/40 via-blue-950/20 to-[#0A0E18] border-[#00F0FF]/30 text-white shadow-2xl relative overflow-hidden">
        <div className="flex flex-col md:flex-row md:items-center justify-between gap-4 relative z-10">
          <div className="space-y-1.5">
            <div className="flex items-center gap-2">
              <span className="p-2 rounded-xl bg-[#00F0FF]/15 text-[#00F0FF] border border-[#00F0FF]/30 flex items-center justify-center">
                <Calendar className="w-5 h-5" />
              </span>
              <span className="text-xs font-mono font-bold tracking-wider text-[#00F0FF] uppercase">
                AI Timetable Architecture
              </span>
              <span className="text-[10px] font-mono px-2 py-0.5 rounded-full bg-emerald-500/20 text-emerald-400 border border-emerald-500/30">
                {timetable.academicTerm}
              </span>
            </div>

            <h1 className="text-2xl md:text-3xl font-black tracking-tight font-sans">
              {timetable.title}
            </h1>
            <p className="text-xs text-slate-300 max-w-xl">
              Intelligent academic scheduling grid. Includes automatic period conflict detection, room routing, and role-calibrated study/lecture allocations.
            </p>
          </div>

          {/* Action Bar */}
          {!isReadOnlyPreview && (
            <div className="flex flex-wrap items-center gap-2.5">
              <button
                type="button"
                onClick={handleAIAutoOptimize}
                className="inline-flex items-center gap-1.5 px-4 py-2.5 rounded-xl bg-[#00F0FF] hover:bg-[#38bdf8] text-black font-bold font-mono text-xs shadow-[0_0_20px_rgba(0,240,255,0.25)] transition-all cursor-pointer active:scale-95"
              >
                <Sparkles className="w-4 h-4" />
                <span>AI Auto-Optimize</span>
              </button>

              <button
                type="button"
                onClick={handleExportJSON}
                className="inline-flex items-center gap-1.5 px-3 py-2.5 rounded-xl bg-white/10 hover:bg-white/15 text-white font-mono text-xs border border-white/15 transition-all cursor-pointer"
                title="Export as JSON"
              >
                <Download className="w-4 h-4" />
                <span>Export</span>
              </button>
            </div>
          )}
        </div>
      </div>

      {/* Conflict / Integrity Sentinel Bar */}
      <div
        className={`p-3.5 rounded-2xl border flex items-center justify-between text-xs font-mono ${
          hasConflicts
            ? 'bg-rose-950/30 border-rose-500/40 text-rose-300'
            : 'bg-emerald-950/20 border-emerald-500/30 text-emerald-300'
        }`}
      >
        <div className="flex items-center gap-2">
          {hasConflicts ? (
            <AlertTriangle className="w-4 h-4 text-rose-400 shrink-0" />
          ) : (
            <CheckCircle2 className="w-4 h-4 text-emerald-400 shrink-0" />
          )}
          <span>
            {hasConflicts
              ? 'Schedule Conflict Detected: Two or more classes are scheduled in the same period.'
              : 'Zero Schedule Conflicts Detected · All periods verified with optimal transition buffers.'}
          </span>
        </div>

        <span className="text-[10px] text-slate-400 hidden sm:inline">
          {timetable.slots.length} Active Slots Monitored
        </span>
      </div>

      {/* Timetable Grid View */}
      <div className={`rounded-3xl border overflow-x-auto ${isDark ? 'bg-[#0B0F19]/90 border-white/10' : 'bg-white border-slate-200'} shadow-2xl`}>
        <table className="w-full border-collapse min-w-[760px]">
          <thead>
            <tr className={`border-b ${isDark ? 'border-white/10 bg-white/[0.02]' : 'border-slate-200 bg-slate-50'}`}>
              <th className="p-3.5 text-left text-[11px] font-mono uppercase text-slate-400 font-bold w-28">
                Time / Period
              </th>
              {timetable.daysOfWeek.map((day) => (
                <th key={day} className="p-3.5 text-left text-xs font-mono uppercase font-bold text-white tracking-wider">
                  {day}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {timetable.periodTimes.map((period, pIdx) => {
              const isBreakPeriod = period.label?.toLowerCase().includes('lunch') || period.label?.toLowerCase().includes('recess');

              return (
                <tr
                  key={period.period}
                  className={`border-b transition-colors ${
                    isBreakPeriod
                      ? 'bg-amber-500/[0.03]'
                      : isDark
                      ? 'border-white/5 hover:bg-white/[0.01]'
                      : 'border-slate-100 hover:bg-slate-50/50'
                  }`}
                >
                  {/* Period Time Column */}
                  <td className="p-3.5 align-top text-xs font-mono text-slate-400 border-r border-white/5">
                    <div className="font-bold text-white">{period.startTime}</div>
                    <div className="text-[10px] text-slate-500">{period.endTime}</div>
                    <div className="text-[9px] uppercase tracking-wider text-slate-400 mt-1">{period.label}</div>
                  </td>

                  {/* Day Columns */}
                  {timetable.daysOfWeek.map((day) => {
                    const matchingSlots = timetable.slots.filter(
                      (s) => s.day === day && s.periodIndex === pIdx
                    );
                    const isConflictCell = matchingSlots.length > 1;

                    return (
                      <td
                        key={day}
                        onClick={() => {
                          if (matchingSlots.length === 0) handleOpenAddSlot(day, pIdx);
                        }}
                        className={`p-2 align-top border-r border-white/5 transition-all ${
                          matchingSlots.length === 0 && !isReadOnlyPreview
                            ? 'cursor-pointer hover:bg-white/[0.04]'
                            : ''
                        }`}
                      >
                        {matchingSlots.length > 0 ? (
                          <div className="space-y-1.5">
                            {matchingSlots.map((slot, msIdx) => {
                              const isBreak = slot.type === 'break';
                              return (
                                <div
                                  key={`${slot.id || 'slot'}-${msIdx}`}
                                  onClick={(e) => {
                                    e.stopPropagation();
                                    if (!isReadOnlyPreview) {
                                      setEditingSlot(slot);
                                      setModalOpen(true);
                                    }
                                  }}
                                  className={`p-2.5 rounded-2xl border transition-all text-left relative group ${
                                    isBreak
                                      ? 'bg-amber-500/10 border-amber-500/30 text-amber-200'
                                      : isConflictCell
                                      ? 'bg-rose-950/40 border-rose-500/50 shadow-[0_0_15px_rgba(244,63,94,0.3)]'
                                      : isDark
                                      ? 'bg-white/[0.04] border-white/10 hover:border-white/30 text-white'
                                      : 'bg-white border-slate-200 shadow-xs'
                                  } ${!isReadOnlyPreview ? 'cursor-pointer hover:scale-[1.02]' : ''}`}
                                >
                                  {/* Left accent bar */}
                                  <div
                                    className="absolute left-0 top-2 bottom-2 w-1 rounded-r-full"
                                    style={{ backgroundColor: slot.color || '#00F0FF' }}
                                  />

                                  <div className="pl-1.5 space-y-1">
                                    <div className="flex items-center justify-between gap-1">
                                      <span className="text-xs font-bold font-sans truncate text-white">
                                        {slot.subject}
                                      </span>
                                      {!isReadOnlyPreview && (
                                        <button
                                          type="button"
                                          onClick={(e) => handleDeleteSlot(slot.id, e)}
                                          className="opacity-0 group-hover:opacity-100 p-1 text-slate-400 hover:text-rose-400 transition-opacity cursor-pointer"
                                          title="Remove Slot"
                                        >
                                          <Trash2 className="w-3 h-3" />
                                        </button>
                                      )}
                                    </div>

                                    {!isBreak && (
                                      <div className="flex flex-wrap items-center gap-2 text-[10px] font-mono text-slate-400">
                                        {slot.courseCode && (
                                          <span className="text-cyan-300 font-bold">{slot.courseCode}</span>
                                        )}
                                        {slot.room && (
                                          <span className="flex items-center gap-0.5">
                                            <Building className="w-2.5 h-2.5" />
                                            <span>{slot.room}</span>
                                          </span>
                                        )}
                                        {slot.instructor && (
                                          <span className="flex items-center gap-0.5 text-slate-400 truncate">
                                            <User className="w-2.5 h-2.5" />
                                            <span>{slot.instructor}</span>
                                          </span>
                                        )}
                                      </div>
                                    )}

                                    {isBreak && (
                                      <div className="text-[10px] font-mono text-amber-300/80 flex items-center gap-1">
                                        <Coffee className="w-3 h-3 text-amber-400" />
                                        <span>Recess Period</span>
                                      </div>
                                    )}
                                  </div>
                                </div>
                              );
                            })}
                          </div>
                        ) : (
                          <div className="h-16 flex items-center justify-center text-slate-600 text-[10px] font-mono group">
                            {!isReadOnlyPreview && (
                              <span className="opacity-0 group-hover:opacity-100 flex items-center gap-1 text-slate-400">
                                <Plus className="w-3 h-3" />
                                <span>Add</span>
                              </span>
                            )}
                          </div>
                        )}
                      </td>
                    );
                  })}
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>

      {/* Add / Edit Slot Modal */}
      {modalOpen && editingSlot && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-md animate-fadeIn">
          <div className="w-full max-w-md rounded-3xl border border-white/20 bg-[#090D16] p-6 text-white space-y-4 shadow-2xl">
            <div className="flex items-center justify-between pb-3 border-b border-white/10">
              <div className="flex items-center gap-2">
                <span className="p-2 rounded-xl bg-[#00F0FF]/15 text-[#00F0FF] border border-[#00F0FF]/30">
                  <Calendar className="w-4 h-4" />
                </span>
                <h3 className="text-sm font-bold font-mono">
                  {timetable.slots.some((s) => s.id === editingSlot.id) ? 'Edit Class Slot' : 'Add Class Slot'}
                </h3>
              </div>
              <button
                type="button"
                onClick={() => setModalOpen(false)}
                className="text-slate-400 hover:text-white p-1 rounded-lg hover:bg-white/10"
              >
                ✕
              </button>
            </div>

            <div className="space-y-3 text-xs font-mono">
              <div>
                <label className="text-[10px] uppercase text-slate-400 font-bold block mb-1">
                  Subject Name *
                </label>
                <input
                  type="text"
                  value={editingSlot.subject}
                  onChange={(e) => setEditingSlot({ ...editingSlot, subject: e.target.value })}
                  placeholder="e.g. Data Structures & Algorithms"
                  className="w-full px-3 py-2 rounded-xl bg-black/40 border border-white/10 text-white placeholder-slate-500 focus:outline-none focus:border-[#00F0FF]"
                />
              </div>

              <div className="grid grid-cols-2 gap-2">
                <div>
                  <label className="text-[10px] uppercase text-slate-400 font-bold block mb-1">
                    Course Code
                  </label>
                  <input
                    type="text"
                    value={editingSlot.courseCode || ''}
                    onChange={(e) => setEditingSlot({ ...editingSlot, courseCode: e.target.value })}
                    placeholder="e.g. CS-402"
                    className="w-full px-3 py-2 rounded-xl bg-black/40 border border-white/10 text-white placeholder-slate-500 focus:outline-none focus:border-[#00F0FF]"
                  />
                </div>

                <div>
                  <label className="text-[10px] uppercase text-slate-400 font-bold block mb-1">
                    Room / Lab
                  </label>
                  <input
                    type="text"
                    value={editingSlot.room || ''}
                    onChange={(e) => setEditingSlot({ ...editingSlot, room: e.target.value })}
                    placeholder="e.g. Hall 301"
                    className="w-full px-3 py-2 rounded-xl bg-black/40 border border-white/10 text-white placeholder-slate-500 focus:outline-none focus:border-[#00F0FF]"
                  />
                </div>
              </div>

              <div>
                <label className="text-[10px] uppercase text-slate-400 font-bold block mb-1">
                  Instructor
                </label>
                <input
                  type="text"
                  value={editingSlot.instructor || ''}
                  onChange={(e) => setEditingSlot({ ...editingSlot, instructor: e.target.value })}
                  placeholder="e.g. Dr. Sarah Lin"
                  className="w-full px-3 py-2 rounded-xl bg-black/40 border border-white/10 text-white placeholder-slate-500 focus:outline-none focus:border-[#00F0FF]"
                />
              </div>

              <div className="grid grid-cols-2 gap-2">
                <div>
                  <label className="text-[10px] uppercase text-slate-400 font-bold block mb-1">
                    Type
                  </label>
                  <select
                    value={editingSlot.type}
                    onChange={(e) => setEditingSlot({ ...editingSlot, type: e.target.value as any })}
                    className="w-full px-3 py-2 rounded-xl bg-black/40 border border-white/10 text-white focus:outline-none focus:border-[#00F0FF]"
                  >
                    <option value="lecture">Lecture</option>
                    <option value="lab">Lab Session</option>
                    <option value="tutorial">Tutorial</option>
                    <option value="break">Lunch / Break</option>
                    <option value="study_block">Study Block</option>
                  </select>
                </div>

                <div>
                  <label className="text-[10px] uppercase text-slate-400 font-bold block mb-1">
                    Color Accent
                  </label>
                  <div className="flex items-center gap-1.5 pt-1">
                    {['#00F0FF', '#A855F7', '#10B981', '#F59E0B', '#EC4899'].map((c) => (
                      <button
                        key={c}
                        type="button"
                        onClick={() => setEditingSlot({ ...editingSlot, color: c })}
                        className={`w-6 h-6 rounded-full border cursor-pointer transition-all ${
                          editingSlot.color === c ? 'border-white scale-110 shadow-md' : 'border-transparent'
                        }`}
                        style={{ backgroundColor: c }}
                      />
                    ))}
                  </div>
                </div>
              </div>
            </div>

            <div className="flex justify-end gap-2 pt-3 border-t border-white/10">
              <button
                type="button"
                onClick={() => setModalOpen(false)}
                className="px-4 py-2 rounded-xl bg-white/5 hover:bg-white/10 text-xs font-mono font-bold"
              >
                Cancel
              </button>
              <button
                type="button"
                onClick={() => handleSaveSlot(editingSlot)}
                className="px-5 py-2 rounded-xl bg-[#00F0FF] hover:bg-[#38bdf8] text-black font-bold font-mono text-xs shadow-[0_0_15px_rgba(0,240,255,0.3)]"
              >
                Save Slot
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
